// Exports the bit patterns of OpenCV's DICT_4X4_250 so sheets can be drawn
// without loading OpenCV. Run once: node scripts/gen-aruco.ts
import { writeFileSync } from 'node:fs';
import { loadCv } from '../src/core/cv.ts';

const cv = await loadCv();
const dict = cv.getPredefinedDictionary(cv.DICT_4X4_250);
const codes: number[] = [];
const img = new cv.Mat();
for (let id = 0; id < 250; id++) {
  // 6x6 px: 1 px border + 4x4 data bits, one pixel per module
  dict.generateImageMarker(id, 6, img, 1);
  let code = 0;
  for (let r = 0; r < 4; r++)
    for (let c = 0; c < 4; c++)
      if (img.data[(r + 1) * 6 + (c + 1)] > 127) code |= 1 << (r * 4 + c);
  codes.push(code);
}
img.delete();

writeFileSync(
  new URL('../src/core/aruco-dict.ts', import.meta.url),
  `// Generated by scripts/gen-aruco.ts from OpenCV DICT_4X4_250. Do not edit.
// Bit (r*4+c) set = white module at data row r, column c.
export const ARUCO_4X4_250 = [${codes.join(',')}];
`,
);
console.log('wrote', codes.length, 'markers');
